import assert from 'node:assert/strict';
import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const svg=fs.readFileSync(path.join(root,'assets/visuals/readme-demo.svg'),'utf8');
assert.match(svg,/^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg"/);
assert.match(svg,/viewBox="0 0 1500 480"/);
assert.match(svg,/role="img" aria-labelledby="demoTitle demoDesc"/);
assert.match(svg,/<title id="demoTitle">/);
assert.match(svg,/prefers-reduced-motion: reduce/);
assert.match(svg,/@keyframes p1/);
assert.match(svg,/duct bank/);
assert.ok(svg.includes("Duct Bank / Electrical"));
assert.match(svg,/Start Smart 10/);
assert.match(svg,/tv-conduit/);
assert.doesNotMatch(svg,/<script\b|<foreignObject\b|<image\b|onload=|https?:\/\/[^\s"<>]*\.(?:png|jpg|woff)/i);
assert.ok(Buffer.byteLength(svg)<300*1024);
execFileSync(process.execPath,[path.join(root,'scripts/build-readme-demo.mjs'),'--check'],{cwd:root,stdio:'inherit'});
console.log('README demo SVG tests passed');
