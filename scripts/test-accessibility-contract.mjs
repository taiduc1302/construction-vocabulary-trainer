import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const index=read('index.html');
const term=read('term.html');
const styles=read('src/styles.css');
const ux=read('src/ux.css');
const app=read('src/app.js');
const onboarding=read('src/public-mode.js');
const termPage=read('src/term-page.js');

assert.match(index,/<a class="skip-link" href="#mainContent">/,'home must offer a keyboard skip link');
assert.match(index,/<main id="mainContent" tabindex="-1">/,'main must be a focusable skip-link target');
assert.match(term,/<a class="skip-link" href="#termPage">/,'term page must offer a skip link');
assert.match(term,/id="termPage" class="term-page" tabindex="-1"/);
assert.match(index,/id="importProgress"[^>]*type="file"[^>]*aria-label="Import progress JSON file"/);
assert.doesNotMatch(styles,/\.file-label input\s*\{\s*display:\s*none/,'progress import must remain keyboard reachable');
assert.match(styles,/\.file-label input\{position:absolute/,'import should be visually hidden, not removed from keyboard flow');
assert.match(ux,/\.file-label:focus-within/,'keyboard focus on the file picker needs a visible label outline');
assert.doesNotMatch(ux,/:focus-visible\{outline:[^}]*rgba\(/,'keyboard outline must not be translucent');
assert.match(ux,/@media\(forced-colors:active\)/,'forced-colors mode needs visible non-color selection');
assert.match(ux,/\.onboarding-choice\.selected/,'selected onboarding choices need high-contrast emphasis');
assert.match(ux,/@media\(prefers-reduced-motion:reduce\)/,'respect reduced motion');
assert.match(ux,/@media\(prefers-color-scheme:dark\)/,'ensure focus and status work on dark surfaces');
assert.match(index,/id="appLoadStatus"[^>]*role="status"/,'loading must be announced');
assert.match(app,/loadStatus\.hidden=true/,'the status must clear after successful initialization');
assert.match(app,/status\.setAttribute\('role','alert'\)/,'loading errors must be announced');
assert.match(app,/id="retryAppLoad"/,'failed load must have a retry control');
assert.match(onboarding,/aria-modal="true"[^>]*aria-describedby="onboardingDescription"/);
assert.match(onboarding,/backgroundNodes\.forEach\(node=>\{node\.inert=true;\}\)/,'background must not be focusable while modal is open');
assert.match(onboarding,/event\.key==='Tab'/,'modal must contain keyboard focus');
assert.match(onboarding,/event\.key==='Escape'/,'modal should support Escape');
assert.match(onboarding,/returnFocus\.isConnected/,'closing a modal must restore focus when possible');
assert.match(onboarding,/closeDialog\(\);\s*applySupportLanguage\(\)/,'submit should close the modal safely');
assert.equal((app.match(/id="feedback" role="status" aria-live="polite" aria-atomic="true"/g)||[]).length,2,'quiz feedback in both question modes must be announced');
assert.match(app,/id="drawingFeedback" role="status" aria-live="polite"/);
assert.match(app,/<h2 class="quiz-question">/,'quiz needs a semantic question heading');
assert.match(term,/class="term-page-loading" role="status"/);
assert.match(termPage,/class="term-not-found" role="alert"/);
assert.match(termPage,/id="retryTermPage"/);
console.log('Accessibility source contract OK: keyboard skip paths, import, dialog focus, states, feedback and display preferences.');
